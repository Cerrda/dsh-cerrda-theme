#!/usr/bin/env node
// Generate src/vendor/number-flow.inline.js from the vendored number-flow 0.6.2
// CJS dist files (src/vendor/package/dist). The output is a single plain-JS
// IIFE that wires the five CJS modules together (stubbing esm-env) and exposes
// the library as window.__CERRDA_NUMBER_FLOW__ for the theme bundle.
//
// Run: node scripts/vendor-number-flow.mjs   (npm run build runs it first)

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const dist = join(root, 'src', 'vendor', 'package', 'dist')
const outPath = join(root, 'src', 'vendor', 'number-flow.inline.js')

// Module ids as they appear in require() calls inside the CJS files.
const MODULES = [
  './ssr-B-DD5oSO.js',
  './plugins.js',
  './lite.js',
  './csp.js',
  './index.js',
]

const header = `/*! number-flow v0.6.2 (MIT) — vendored for dsh-cerrda-theme.
 * Source: https://github.com/barvian/number-flow (see src/vendor/package/LICENSE.md).
 * This file is GENERATED by scripts/vendor-number-flow.mjs — do not edit. */
window.__CERRDA_NUMBER_FLOW__ = (function () {
  var esmEnv = { BROWSER: true, DEV: false, BUILD: true };
  var modules = {};
  function define(id, factory) {
    var m = { exports: {} };
    modules[id] = m;
    factory(m, m.exports, function (dep) {
      if (dep === 'esm-env') return esmEnv;
      return modules[dep].exports;
    });
    return m.exports;
  }
`

const footer = `  return modules['./index.js'].exports;
})();
`

const bodies = MODULES.map((id) => {
  const src = readFileSync(join(dist, id), 'utf8').replace(/\r\n/g, '\n')
  return `  define('${id}', function (module, exports, require) {\n${src}\n  });\n`
}).join('')

writeFileSync(outPath, header + bodies + footer, 'utf8')
console.log(`generated ${outPath} (${Buffer.byteLength(header + bodies + footer)} bytes)`)
